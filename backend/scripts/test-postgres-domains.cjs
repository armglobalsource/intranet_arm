require('dotenv').config({path:['.env.supabase','.env'],quiet:true});
require('ts-node/register');
require('reflect-metadata');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {Pool}=require('pg');
const {buildPostgresOptions}=require('../src/common/database/postgres-options');
const {PostgresCampusService}=require('../src/campus/postgres-campus.service');
const {PostgresArmCatalogosService}=require('../src/arm-catalogos/postgres-arm-catalogos.service');
const {PostgresJobTitlesService}=require('../src/job-titles/postgres-job-titles.service');
const {PostgresOnboardingService}=require('../src/onboarding/postgres-onboarding.service');
const {PostgresCancionesService}=require('../src/canciones/postgres-canciones.service');
const {PostgresPaletasService}=require('../src/paletas/postgres-paletas.service');
const {PostgresDisponibilidadService,PostgresTecnicosService}=require('../src/disponibilidad/postgres-availability');
const {PostgresCampusTurnosService}=require('../src/campus-turnos/postgres-campus-turnos.service');
const {PostgresOrgChartService}=require('../src/orgchart/postgres-orgchart.service');
const {PostgresUsersService}=require('../src/users/postgres-users.service');
const {PostgresContentsService}=require('../src/content/postgres-content.service');
const {PostgresDocumentsService}=require('../src/documents/postgres-documents.service');
const {PostgresSearchService}=require('../src/search/postgres-search.service');
const {PostgresFeedbackService}=require('../src/feedback/postgres-feedback.service');
const {PostgresVisualReferencesService}=require('../src/visual-references/postgres-visual-references.service');
const {PostgresTipoCambioService}=require('../src/tipo-cambio/postgres-tipo-cambio.service');
const {ArmRecordStore}=require('../src/common/database/arm-record-store');
const {PostgresEncuentrosService}=require('../src/encuentros/postgres-encuentros.service');
const {PostgresKiloamorService}=require('../src/kiloamor/postgres-kiloamor.service');
const {PostgresSiembraService}=require('../src/siembra/postgres-siembra.service');
const {PostgresAnunciosService}=require('../src/anuncios/postgres-anuncios.service');
const {PostgresEventsService}=require('../src/events/postgres-events.service');
const {PostgresEstadisticasService}=require('../src/estadisticas/postgres-estadisticas.service');
const {PostgresReconciliationService}=require('../src/reconciliation/postgres-reconciliation.service');
const {PostgresEquipoRosterService}=require('../src/equipo-roster/postgres-equipo-roster.service');
const {assertRuntimeSchema}=require('../src/common/database/runtime-schema');
let phase='connect';
async function main() {
  const pool=new Pool(buildPostgresOptions(process.env.DATABASE_URL,process.env.DATABASE_CA_CERT));
  const client=await pool.connect();let sequence=0;
  const db={query:client.query.bind(client),transaction:async operation=>{
    const savepoint=`domain_test_${++sequence}`;await client.query(`SAVEPOINT ${savepoint}`);
    try {const result=await operation(client);await client.query(`RELEASE SAVEPOINT ${savepoint}`);return result;}
    catch(error) {await client.query(`ROLLBACK TO SAVEPOINT ${savepoint}`);await client.query(`RELEASE SAVEPOINT ${savepoint}`);throw error;}
  }};
  const marker='domain-test-'+randomUUID();
  const catalogs=new PostgresArmCatalogosService(db);
  const campuses=new PostgresCampusService(db,catalogs);
  const jobs=new PostgresJobTitlesService(db);
  const users=new PostgresUsersService(db,{},{});
  const org=new PostgresOrgChartService(db,{},users);
  const availability=new PostgresDisponibilidadService(db,campuses);
  const technicians=new PostgresTecnicosService(db,campuses);
  const shifts=new PostgresCampusTurnosService(db);
  const songs=new PostgresCancionesService(db);
  const palettes=new PostgresPaletasService(db);
  const onboarding=new PostgresOnboardingService(db);
  try {
    await client.query('BEGIN');phase='catalogs and campuses';
    await catalogs.create({tipo:'asistencia',key:marker,label:'Test category'});
    await assert.rejects(db.transaction(()=>catalogs.create({tipo:'asistencia',key:marker.toUpperCase(),label:'Duplicate'})),e=>e.getStatus()===409);
    const schedules=[{dia:'Domingo',hora:'09:00',bloque:'AM'},{dia:'Domingo',hora:'11:00',bloque:'AM'}];
    const a=await campuses.create({name:marker+' A',schedules});
    const b=await campuses.create({name:marker+' B',schedules});
    assert(a.asistenciaCategoriaKeys.includes(marker));
    assert.equal((await campuses.findByName(a.name.toUpperCase())).id,a.id);
    phase='job titles and organigram';
    const job=await jobs.create({name:marker});
    const user=await users.create({email:marker+'@example.invalid',firstName:'Domain',lastName:'Test',roleId:2,campusId:a.id,jobTitleIds:[job.id]},0);
    const area=await org.createArea({slug:marker,name:marker,color:'#ffffff',icon:'A'});
    const team=await org.createTeam({areaId:area.id,name:marker});
    const child=await org.createTeam({areaId:area.id,parentTeamId:team.id,name:marker+' child'});
    await org.createMembership({userId:user.id,teamId:child.id,role:'member',jobTitleId:job.id});
    let tree=await org.getAreaTree(marker);
    assert.equal(tree.teams[0].children[0].memberships[0].user.id,user.id);
    assert.equal(tree.teams[0].children[0].memberships[0].user.passwordHash,undefined);
    assert.equal((await org.search(marker)).length,1);
    await jobs.update(job.id,{name:marker+' renamed'});
    const affected=await jobs.getAffectedUsers(job.id);
    assert.deepEqual(affected[0].sources,['manual','orgchart']);
    assert.equal((await users.rawById(user.id)).jobTitles[0].name,marker+' renamed');
    await jobs.remove(job.id);
    assert.deepEqual((await users.rawById(user.id)).jobTitles,[]);
    assert.equal((await org.getUserOrgProfile(user.id)).orgMemberships[0].jobTitle,null);
    phase='availability';
    const dto={campusId:a.id,weekLabel:'2026-W43',slots:[{scheduleKey:'Domingo_AM',available:true,nota:'original'}]};
    const first=await availability.bulkSubmit(user.id,'Domain Test',dto);
    const second=await availability.bulkSubmit(user.id,'Domain Test',{...dto,slots:[{...dto.slots[0],nota:'updated'}]});
    assert.equal(first[0].id,second[0].id);
    assert.equal(first[0].hora,'09:00 · 11:00');
    const other=await availability.bulkSubmit(user.id,'Domain Test',{...dto,campusId:b.id});
    assert.notEqual(other[0].id,first[0].id);
    await assert.rejects(availability.bulkSubmit(user.id,'Domain Test',{...dto,slots:[{...dto.slots[0],available:false},{scheduleKey:'invalid',available:true}]}),e=>e.getStatus()===400);
    assert.equal((await availability.getMyWeek(user.id,a.id,dto.weekLabel))[0].available,true);
    assert.equal((await availability.getMatrix(a.id,dto.weekLabel)).volunteers.length,1);
    await technicians.bulkSubmit(user.id,'Domain Test',dto);
    assert.equal((await technicians.getMatrix(a.id,dto.weekLabel)).tecnicos.length,1);
    phase='shift generation';
    const admin=await shifts.createAdministrador({campusId:a.id,tipo:'administradores',nombre:'Test'});
    const adminB=await shifts.createAdministrador({campusId:b.id,tipo:'administradores',nombre:'Other campus'});
    await assert.rejects(shifts.createEquipo({campusId:a.id,tipo:'administradores',nombre:'Invalid',administradorIds:[adminB.id]}),e=>e.getStatus()===400);
    const group=await shifts.createEquipo({campusId:a.id,tipo:'administradores',nombre:'Test 1',administradorIds:[admin.id]});
    const group2=await shifts.createEquipo({campusId:a.id,tipo:'administradores',nombre:'Test 2',administradorIds:[admin.id]});
    const generation={campusId:a.id,tipo:'administradores',equipoIds:[group.id],fechaInicio:'2026-10-19',semanas:3};
    assert.equal((await shifts.generar(generation)).creados,3);
    let turns=await shifts.findTurnos(a.id,'administradores');assert.equal(turns[0].fecha,'2026-10-19');
    const changed=await shifts.updateTurno(turns[0].id,{equipoId:group2.id});assert.equal(changed.fecha,'2026-10-19');
    assert.equal((await shifts.generar(generation)).creados,0);
    turns=await shifts.findTurnos(a.id,'administradores');assert.equal(turns[0].equipoId,group2.id);assert(turns[0].isManualOverride);
    phase='songs palettes onboarding';
    const song=await songs.upsert({titulo:marker,tonalidad:'C'});
    const song2=await songs.upsert({titulo:marker.toUpperCase(),tonalidad:'D'});
    assert.equal(song.fichaId,song2.fichaId);assert.equal(song2.usageCount,2);assert.equal(song2.tonalidad,'C');
    const palette=await palettes.create({name:marker,colors:[{name:'white',hex:'#ffffff'}]});
    assert((await palettes.findAll()).some(p=>p.id===palette.id));
    const welcome=await onboarding.create({teamName:marker,slug:marker,roleNames:['domain-test-role'],steps:[]});
    assert(!(await onboarding.findAll('user')).some(o=>o.id===welcome.id));
    assert((await onboarding.findAll('domain-test-role')).some(o=>o.id===welcome.id));
    const welcome2=await onboarding.create({teamName:marker+' other',slug:marker+'-other',roleNames:[],steps:[]});
    await assert.rejects(db.transaction(()=>onboarding.update(welcome.id,{slug:welcome2.slug})),e=>e.getStatus()===409);
    phase='content document visibility and search';
    await client.query("UPDATE arm_app.users SET status='active' WHERE id=$1",[user.id]);
    const restrictedRole=await client.query("INSERT INTO arm_app.roles(id,document_id,name,permissions) SELECT v,v::text,$1,'[]'::jsonb FROM nextval(pg_get_serial_sequence('arm_app.roles','id')) v RETURNING id",[marker]);
    await client.query('UPDATE arm_app.users SET "roleId"=$2 WHERE id=$1',[user.id,restrictedRole.rows[0].id]);
    const content=new PostgresContentsService(db),documents=new PostgresDocumentsService(db),search=new PostgresSearchService(db);
    const news=await content.create({title:marker,body:'Test',type:'news',campusId:String(a.id)},user.id);
    await assert.rejects(content.findOne(news.id,{sub:user.id}),e=>e.getStatus()===403);
    assert(!(await content.findAll(user.id)).some(x=>x.id===news.id));
    await content.update(news.id,{status:'published'});
    assert.equal((await content.findOne(news.id,{sub:user.id})).id,news.id);
    await content.update(news.id,{campusId:String(b.id)});
    assert(!(await search.globalSearch(marker,user.id)).content.some(x=>x.id===news.id));
    await content.update(news.id,{campusId:null});
    assert((await search.globalSearch(marker,user.id)).content.some(x=>x.id===news.id));
    const document=await documents.create({name:marker,description:'Test',minRoleId:1},user.id);
    await assert.rejects(documents.findOne(document.id,{sub:user.id}),e=>e.getStatus()===403);
    assert(!(await search.globalSearch(marker,user.id)).documents.some(x=>x.id===document.id));
    await documents.update(document.id,{minRoleId:null});
    assert((await search.globalSearch(marker,user.id)).documents.some(x=>x.id===document.id));
    assert.equal((await search.globalSearch(marker,user.id)).users.length,0);
    const notifications={create:async()=>({}),createForPermission:async()=>({})};
    const feedback=new PostgresFeedbackService(db,{},notifications);
    const report=await feedback.create({type:'bug',message:marker},user.id,'Test',marker+'@example.invalid');
    assert((await feedback.findMine(user.id)).some(x=>x.id===report.id));
    assert.equal((await feedback.updateStatus(report.id,{status:'resolved',note:'Fixed'},user.id,'Test')).resolvedBy,user.id);
    await feedback.remove(report.id);await documents.remove(document.id);await content.remove(news.id);
    phase='visual catalog and exchange rates';
    const visual=new PostgresVisualReferencesService(db,{uploadPublic:async()=> 'https://example.invalid/test.png'});
    const reference=await visual.create({name:marker,tags:'Blue, blue, Worship'},{mimetype:'image/png',buffer:Buffer.from([])},user.id,'Test');
    assert.deepEqual(reference.tags,['blue','worship']);
    await visual.incrementUsage(reference.id);assert.equal((await visual.findOne(reference.id)).usageCount,1);
    assert((await visual.findAll(marker)).some(x=>x.id===reference.id));
    await visual.update(reference.id,{tags:'test'});await visual.remove(reference.id);
    const currency=new PostgresTipoCambioService(db),originalFetch=global.fetch;
    try {
      global.fetch=async()=>({ok:true,json:async()=>({rates:{USD:1,CLP:900,EUR:0.9}})});
      await currency.refreshFromApi();
      assert.equal((await currency.getTasasClp(['EUR'])).tasas.EUR.clpPorUnidad,1000);
      await currency.setManual('EUR',{clpPorUnidad:1100},{sub:String(user.id),email:'test@example.invalid'});
      assert.equal((await currency.getTasasClp(['EUR'])).tasas.EUR.clpPorUnidad,1100);
      await currency.clearManual('EUR');assert.equal((await currency.getTasasClp(['EUR'])).tasas.EUR.fuente,'api');
    } finally {global.fetch=originalFetch;}
    phase='ARM records and statistics';
    await assertRuntimeSchema(db);
    const store=new ArmRecordStore(db),actor={sub:String(user.id),email:'test@example.invalid'};
    const encounters=new PostgresEncuentrosService(store,campuses),kilos=new PostgresKiloamorService(store,campuses);
    const recordDto={campus:a.name,fecha:'2026-10-21',tipo:'encuentro',encuentro:'Encuentro I · 09:00',asistencia:{auditorio:30},voluntarios:{servicio:4},idempotencyKey:marker};
    const reporter={...actor,campusId:a.id,permissions:['encuentros:create']};
    const encounter=await encounters.create(recordDto,reporter);
    assert.equal((await encounters.create(recordDto,reporter)).id,encounter.id,'a retry with the same key returns the same record');
    await assert.rejects(encounters.create({...recordDto,idempotencyKey:marker+'-2',encuentro:'encuentro i · 09:00'},reporter),e=>e.getStatus()===409,'the same encuentro cannot be reported twice');
    await assert.rejects(encounters.create({...recordDto,idempotencyKey:marker+'-3',campus:'Otro campus'},reporter),e=>e.getStatus()===403,'a campus reports only itself');
    await assert.rejects(encounters.create({...recordDto,idempotencyKey:marker+'-4',fecha:'21-10-2026'},reporter),e=>e.getStatus()===400);
    const {assertRecordCampus}=require('../src/encuentros/encuentros.scope');
    assert.throws(()=>assertRecordCampus(encounter,{...reporter,campusId:-1}),e=>e.getStatus()===403);
    assertRecordCampus(encounter,{...reporter,campusId:-1,permissions:['estadisticas:viewAll']});
    assert.equal(encounter.totalAsistencia,30);
    assert.equal(encounter.estado,'enviado','a new report waits for the campus administrator');
    const campusAdmin={...actor,sub:-77,campusId:a.id,permissions:['encuentros:review']};
    await assert.rejects(encounters.subir(encounter.id,{...campusAdmin,campusId:-1}),e=>e.getStatus()===403,'only the administrator of that campus reviews');
    assert.equal((await encounters.observar(encounter.id,'Falta Kids',campusAdmin)).estado,'observado');
    assert.equal((await encounters.update(encounter.id,{asistencia:{auditorio:35}},reporter)).estado,'enviado','the author fixes it and it goes back to review');
    assert.equal((await encounters.subir(encounter.id,campusAdmin)).estado,'subido');
    await assert.rejects(encounters.update(encounter.id,{asistencia:{auditorio:1}},reporter),e=>e.getStatus()===403,'an uploaded report is locked for the author');
    assert(!(await encounters.revision(campusAdmin)).items.some(r=>r.id===encounter.id));
    await encounters.update(encounter.id,{asistencia:{auditorio:40}},campusAdmin);
    assert.equal((await encounters.resumen(a.name,2026,10)).encuentros.totalAsistencia,40);
    assert((await encounters.findMine(user.id)).some(r=>r.id===encounter.id));
    const kilo=await kilos.create({campus:a.name,fecha:'2026-10-21',cajas:3,idempotencyKey:marker},actor);
    assert.equal((await kilos.resumen(a.name,2026,10)).totalCajas,3);
    const stats=new PostgresEstadisticasService(store,campuses,catalogs);
    const dashboard=await stats.dashboard({year:2026,groupBy:'month',type:'all',campusId:a.id,canViewAll:false});
    assert.equal(dashboard.totals.asistencia,40);assert.equal(dashboard.totals.kiloAmorCajas,3);
    const siembra=new PostgresSiembraService(store,{getTasasClp:async()=>({tasas:{USD:{clpPorUnidad:900}},actualizadoApi:null})},catalogs);
    const contribution=await siembra.create({campus:a.name,fecha:'2026-10-21',montos:[{moneda:'CLP',efectivo:{ofrendas:100,diezmos:[{monto:50}]},sumup:{ofrendas:20}}],idempotencyKey:marker},actor);
    assert.equal(contribution.montos[0].total,170);
    assert.equal((await siembra.create({campus:a.name,fecha:'2026-10-21',montos:[],idempotencyKey:marker},actor)).id,contribution.id);
    assert.equal((await siembra.dashboard(2026,'month',a.name)).meta.recordCount,1);
    const anuncios=new PostgresAnunciosService(store),events=new PostgresEventsService(store);
    const anuncio=await anuncios.create({titulo:marker,texto:'Test',campus:a.name},actor);
    assert((await anuncios.findActive(a.name)).some(r=>r.id===anuncio.id));await anuncios.deactivate(anuncio.id);
    assert(!(await anuncios.findActive(a.name)).some(r=>r.id===anuncio.id));
    const event=await events.create({title:marker,date:'2026-10-21',category:'encuentro'},user.id);
    assert((await events.findAll('2026')).some(r=>r.id===event.id));await events.update(event.id,{title:marker+' updated'});
    const roster=await new PostgresEquipoRosterService(db,org,availability,technicians).getRoster(a.id,'2026-W43');
    assert(Object.values(roster).flat().some(r=>r.userId===user.id));
    const reconciliation=new PostgresReconciliationService(db,users,campuses);
    assert.equal((await reconciliation.match([{rowKey:'test',nombreCompleto:'Domain Test',campus:a.name}]))[0].resolvedCampusId,a.id);
    await events.remove(event.id);await anuncios.remove(anuncio.id);await siembra.remove(contribution.id);await kilos.remove(kilo.id);await encounters.remove(encounter.id,{...actor,permissions:['*']});
    console.log('PASS: catalogs, campus defaults, job title cascades, nested organigram, availability isolation/atomicity, technicians, shifts/idempotence/manual edits, songs, palettes, onboarding, content/document visibility, scoped search, feedback, visual catalog, currency, ARM records, retry keys, statistics, events, roster and reconciliation.');
  } finally {await client.query('ROLLBACK');client.release();await pool.end();}
}
main().catch(error=>{console.error(`Domain integration failed at ${phase} (${error.code??error.name??'error'}). No rows or credentials logged.`);process.exitCode=1;});
