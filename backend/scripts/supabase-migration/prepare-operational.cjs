const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { model, references } = require('./operational-model.cjs');
const q = value => '"' + value.replaceAll('"', '""') + '"';
const literal = value => "'" + value.replaceAll("'", "''") + "'";
const table = name => `arm_app.${q(name)}`;

function sourceName(record) {
  const parts = record.path.split('/');
  if (parts.length === 4 && parts[0] === 'fichas' && parts[2] === 'changelog') return 'ficha_changelog';
  if (parts.length !== 2) throw new Error('Unexpected subcollection');
  if (parts[0] === 'tipo_cambio' && parts[1] === '_meta') return 'tipo_cambio_meta';
  return parts[0];
}

function validate(records) {
  const counts = {};
  for (const record of records) {
    if (!record.exists) throw new Error('Missing documents require explicit treatment');
    const name = sourceName(record);
    if (name === '_counters') continue;
    const fields = model[name];
    if (!fields) throw new Error(`Unmodelled collection: ${name}`);
    counts[name] = (counts[name] || 0) + 1;
    for (const [key, value] of Object.entries(record.fields.value)) {
      const type = fields[key];
      if (!type) throw new Error(`Unmodelled field: ${name}.${key}`);
      if (value.type === 'null') continue;
      const accepted = { text: ['string'], date: ['string'], bigint: ['number', 'string'], numeric: ['number'], boolean: ['boolean'], jsonb: ['map', 'array'], timestamptz: ['timestamp'] }[type];
      if (!accepted.includes(value.type)) throw new Error(`Wrong type: ${name}.${key}`);
      if (type === 'bigint' && !/^-?\d+$/.test(String(value.value))) throw new Error('Noninteger value');
    }
  }
  return counts;
}

function schemaSQL() {
  const out = [`-- Generated by prepare-operational.cjs from the reviewed operational model.
CREATE SCHEMA arm_app;
REVOKE ALL ON SCHEMA arm_app FROM PUBLIC, anon, authenticated, service_role;
CREATE TABLE arm_migration.operational_loads (
  run_sha256 text PRIMARY KEY REFERENCES arm_migration.runs(run_sha256),
  loaded_at timestamptz NOT NULL DEFAULT now(),
  counts jsonb NOT NULL
);
ALTER TABLE arm_migration.operational_loads ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON arm_migration.operational_loads FROM PUBLIC, anon, authenticated, service_role;
-- Keep nanoseconds in JSON values. PostgreSQL timestamp columns use microseconds;
-- source_timestamps retains the exact original seconds/nanoseconds per field.
CREATE FUNCTION arm_migration.decode_value(v jsonb) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE STRICT SET search_path = pg_catalog AS $$
DECLARE result jsonb; item record; kind text := v->>'type';
BEGIN
  CASE kind
    WHEN 'null' THEN RETURN 'null'::jsonb;
    WHEN 'string', 'boolean' THEN RETURN v->'value';
    WHEN 'number' THEN
      IF jsonb_typeof(v->'value') <> 'number' THEN RAISE EXCEPTION 'Special number needs explicit mapping'; END IF;
      RETURN v->'value';
    WHEN 'timestamp' THEN RETURN to_jsonb(to_char(to_timestamp((v->>'seconds')::bigint) AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS') || '.' || lpad(v->>'nanoseconds',9,'0') || 'Z');
    WHEN 'array' THEN
      result := '[]'::jsonb;
      FOR item IN SELECT value FROM jsonb_array_elements(v->'value') LOOP
        result := result || jsonb_build_array(arm_migration.decode_value(item.value));
      END LOOP;
      RETURN result;
    WHEN 'map' THEN
      result := '{}'::jsonb;
      FOR item IN SELECT key,value FROM jsonb_each(v->'value') LOOP
        result := result || jsonb_build_object(item.key,arm_migration.decode_value(item.value));
      END LOOP;
      RETURN result;
    ELSE RAISE EXCEPTION 'Unsupported encoded type';
  END CASE;
END $$;
REVOKE ALL ON FUNCTION arm_migration.decode_value(jsonb) FROM PUBLIC, anon, authenticated, service_role;`];
  for (const [name, fields] of Object.entries(model)) {
    const columns = [
      'document_id text NOT NULL UNIQUE',
      'source_path text UNIQUE',
      'source_run_sha256 text',
      'source_record_sha256 text',
      'source_fields text[]',
      'source_timestamps jsonb',
      ...Object.entries(fields).map(([key, type]) => `${q(key)} ${type}${key === 'id' ? (type === 'bigint' ? ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : ' PRIMARY KEY') : ''}`),
    ];
    if (!fields.id) columns.push('PRIMARY KEY (document_id)');
    if (name === 'ficha_changelog') columns.push('ficha_document_id text NOT NULL REFERENCES arm_app.fichas(document_id)');
    out.push(`CREATE TABLE ${table(name)} (\n  ${columns.join(',\n  ')}\n);\nALTER TABLE ${table(name)} ENABLE ROW LEVEL SECURITY;`);
  }
  for (const [name, fields] of Object.entries(references)) for (const [field, target] of Object.entries(fields)) {
    out.push(`ALTER TABLE ${table(name)} ADD FOREIGN KEY (${q(field)}) REFERENCES ${table(target)}(id);`);
    out.push(`CREATE INDEX ON ${table(name)} (${q(field)});`);
  }
  out.push(`CREATE INDEX ON arm_app.ficha_changelog (ficha_document_id, "timestamp" DESC);
CREATE UNIQUE INDEX ON arm_app.users (lower(btrim(email))) WHERE email IS NOT NULL AND btrim(email) <> '';
CREATE UNIQUE INDEX ON arm_app.campus_turnos ("campusId", tipo, modalidad, fecha) NULLS NOT DISTINCT;
CREATE UNIQUE INDEX ON arm_app.disponibilidades ("userId", "campusId", "weekLabel", "scheduleKey");
CREATE INDEX ON arm_app.fichas ("campusId", date DESC);
CREATE INDEX ON arm_app.notifications ("userId", "createdAt" DESC);
CREATE INDEX ON arm_app.refresh_tokens ("tokenHash");
CREATE INDEX ON arm_app.refresh_tokens ("expiresAt");
CREATE TABLE arm_migration.unresolved_notifications (
  source_path text PRIMARY KEY,
  run_sha256 text NOT NULL REFERENCES arm_migration.runs(run_sha256),
  reason text NOT NULL,
  raw_record text NOT NULL
);
ALTER TABLE arm_migration.unresolved_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON arm_migration.unresolved_notifications FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA arm_app FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA arm_app FROM PUBLIC, anon, authenticated, service_role;`);
  return out.join('\n\n') + '\n';
}

function importSQL(sha) {
  if (!/^[a-f0-9]{64}$/.test(sha)) throw new Error('Invalid run checksum');
  const out = [`BEGIN;
SET LOCAL statement_timeout = '120s';
SELECT pg_advisory_xact_lock(721936402);
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM arm_migration.runs WHERE run_sha256 = '${sha}' AND status = 'verified' AND source_project_id = 'intranet-arm' AND target_project_ref = 'kqqufmijfvrgzrfrqsby') THEN RAISE EXCEPTION 'Verified source run not found'; END IF;
 IF EXISTS (SELECT 1 FROM arm_migration.operational_loads) THEN RAISE EXCEPTION 'Operational import already performed; refusing overwrite'; END IF;
 IF (SELECT encode(sha256(convert_to(string_agg(raw_record || E'\\n','' ORDER BY source_ordinal),'UTF8')),'hex') FROM arm_migration.source_documents WHERE run_sha256 = '${sha}') IS DISTINCT FROM '${sha}' THEN RAISE EXCEPTION 'Archive checksum mismatch'; END IF;
END $$;`];
  const countEntries = [];
  for (const [name, fields] of Object.entries(model)) {
    let predicate = `array_length(string_to_array(s.path,'/'),1)=2 AND split_part(s.path,'/',1)=${literal(name)}`;
    if (name === 'ficha_changelog') predicate = `s.path ~ '^fichas/[^/]+/changelog/[^/]+$'`;
    if (name === 'tipo_cambio') predicate += ` AND split_part(s.path,'/',2) <> '_meta'`;
    if (name === 'tipo_cambio_meta') predicate = `s.path = 'tipo_cambio/_meta'`;
    if (name === 'notifications') predicate += ` AND EXISTS (SELECT 1 FROM arm_app.users u WHERE u.id = (s.raw_record::jsonb #>> '{fields,value,userId,value}')::bigint)`;
    const cols = ['document_id', 'source_path', 'source_run_sha256', 'source_record_sha256', 'source_fields', 'source_timestamps', ...Object.keys(fields)];
    const values = [name === 'ficha_changelog' ? `split_part(s.path,'/',4)` : `split_part(s.path,'/',2)`, 's.path', 's.run_sha256', 's.record_sha256', `(SELECT array_agg(key ORDER BY key) FROM jsonb_each(f))`, `(SELECT coalesce(jsonb_object_agg(key,value),'{}'::jsonb) FROM jsonb_each(f) WHERE value->>'type'='timestamp')`];
    for (const [key, type] of Object.entries(fields)) {
      const value = `arm_migration.decode_value(f->${literal(key)})`;
      values.push(type === 'jsonb' ? `nullif(${value},'null'::jsonb)` : `((${value}) #>> '{}')::${type}`);
    }
    if (name === 'ficha_changelog') { cols.push('ficha_document_id'); values.push(`split_part(s.path,'/',2)`); }
    const expected = `SELECT ${values.map((v,i)=>`${v} AS ${q(cols[i])}`).join(', ')} FROM arm_migration.source_documents s CROSS JOIN LATERAL (SELECT s.raw_record::jsonb #> '{fields,value}' AS f) decoded WHERE s.run_sha256='${sha}' AND s.source_exists AND ${predicate}`;
    out.push(`LOCK TABLE ${table(name)} IN ACCESS EXCLUSIVE MODE;
DO $$ BEGIN IF EXISTS (SELECT 1 FROM ${table(name)}) THEN RAISE EXCEPTION 'Target ${name} not empty'; END IF; END $$;
INSERT INTO ${table(name)} (${cols.map(q).join(', ')}) ${expected};
DO $$ BEGIN
 IF EXISTS ((SELECT ${cols.map(q).join(', ')} FROM ${table(name)} EXCEPT ${expected}) UNION ALL (${expected} EXCEPT SELECT ${cols.map(q).join(', ')} FROM ${table(name)})) THEN RAISE EXCEPTION 'Value reconciliation failed: ${name}'; END IF;
END $$;`);
    if (fields.id === 'bigint') out.push(`SELECT setval(pg_get_serial_sequence('${table(name)}','id'), greatest(coalesce((SELECT max(id)+1 FROM ${table(name)}),1),coalesce((SELECT (raw_record::jsonb #>> '{fields,value,next,value}')::bigint FROM arm_migration.source_documents WHERE run_sha256='${sha}' AND path='_counters/${name}'),1)), false);`);
    countEntries.push(`${literal(name)}, (SELECT count(*) FROM ${table(name)})`);
  }
  out.push(`INSERT INTO arm_migration.unresolved_notifications(source_path,run_sha256,reason,raw_record)
SELECT path, run_sha256, 'Recipient does not exist; original notification preserved', raw_record FROM arm_migration.source_documents s WHERE run_sha256='${sha}' AND path ~ '^notifications/[^/]+$' AND NOT EXISTS(SELECT 1 FROM arm_app.users u WHERE u.id=(s.raw_record::jsonb #>> '{fields,value,userId,value}')::bigint);
DO $$ DECLARE loaded bigint; expected bigint; BEGIN
 SELECT ${Object.keys(model).map(n=>`(SELECT count(*) FROM ${table(n)})`).join('+')} + (SELECT count(*) FROM arm_migration.unresolved_notifications WHERE run_sha256='${sha}') INTO loaded;
 SELECT count(*) INTO expected FROM arm_migration.source_documents WHERE run_sha256='${sha}' AND source_exists AND path NOT LIKE '_counters/%';
 IF loaded <> expected THEN RAISE EXCEPTION 'Total reconciliation failed'; END IF;
END $$;
INSERT INTO arm_migration.operational_loads(run_sha256,counts) VALUES ('${sha}', jsonb_build_object(${countEntries.join(', ')}, 'unresolved_notifications', (SELECT count(*) FROM arm_migration.unresolved_notifications)));
COMMIT;
SELECT counts FROM arm_migration.operational_loads WHERE run_sha256='${sha}';`);
  return out.join('\n\n') + '\n';
}

function prepare(input, output) {
  const manifest = JSON.parse(fs.readFileSync(path.join(input,'manifest.json'),'utf8'));
  const raw = fs.readFileSync(path.join(input,'documents.jsonl'));
  if (manifest.sourceProjectId !== 'intranet-arm' || createHash('sha256').update(raw).digest('hex') !== manifest.sha256) throw new Error('Wrong source or checksum');
  const records = raw.toString('utf8').trim().split('\n').map(JSON.parse);
  if (records.length !== manifest.documentCount || manifest.missingParentCount !== 0) throw new Error('Invalid counts');
  const counts = validate(records);
  fs.mkdirSync(output, { recursive: true });
  fs.writeFileSync(path.join(output,'operational-schema.sql'),schemaSQL());
  fs.writeFileSync(path.join(output,'operational-import.sql'),importSQL(manifest.sha256));
  console.log(JSON.stringify({ collections: Object.keys(counts).length, documents: Object.values(counts).reduce((a,b)=>a+b,0), counts }));
}
if (require.main === module) {
  if (!process.argv[2] || !process.argv[3]) throw new Error('Usage: prepare-operational.cjs EXPORT_DIRECTORY OUTPUT_DIRECTORY');
  prepare(process.argv[2],process.argv[3]);
}
module.exports = { sourceName, validate, schemaSQL, importSQL };
