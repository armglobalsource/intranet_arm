CREATE TABLE arm_app.arm_catalogos (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id text NOT NULL UNIQUE,
 tipo text NOT NULL CHECK(tipo IN ('asistencia','voluntarios','moneda')),
 key text NOT NULL,"keyLower" text NOT NULL,label text NOT NULL,
 "sortOrder" bigint NOT NULL DEFAULT 0,"isActive" boolean NOT NULL DEFAULT true,
 "createdAt" timestamptz NOT NULL DEFAULT now(),"updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ON arm_app.arm_catalogos(tipo,lower(btrim(key)));
ALTER TABLE arm_app.arm_catalogos ENABLE ROW LEVEL SECURITY;
