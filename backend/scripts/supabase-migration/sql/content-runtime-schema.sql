ALTER TABLE arm_app.content ADD COLUMN IF NOT EXISTS "videoUrl" text;
ALTER TABLE arm_app.content ADD COLUMN IF NOT EXISTS "instagramUrl" text;
CREATE TABLE arm_app.documents (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 document_id text NOT NULL UNIQUE,
 name text NOT NULL, description text, "departmentId" bigint,
 "minRoleId" bigint REFERENCES arm_app.roles(id),
 "uploadedBy" bigint REFERENCES arm_app.users(id),
 status text NOT NULL DEFAULT 'active' CHECK(status IN ('active','archived')),
 "mimeType" text, "sizeBytes" bigint,
 "createdAt" timestamptz NOT NULL DEFAULT now(), "updatedAt" timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE arm_app.documents ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON arm_app.documents FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON SEQUENCE arm_app.documents_id_seq FROM PUBLIC,anon,authenticated,service_role;
CREATE INDEX documents_uploaded_by_idx ON arm_app.documents("uploadedBy");
CREATE INDEX documents_min_role_idx ON arm_app.documents("minRoleId");
